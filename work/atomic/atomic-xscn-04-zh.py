KEEP = set()  # 本片无「原样保留」条目（全部为可音译地名/战役名）


def main():
    src = io.open(SRC, encoding='utf-8', newline='').read().replace('\r\n', '\n').split('\n')
    if src and src[-1] == '':
        src = src[:-1]
    out = []
    miss = []
    for s in src:
        if s in M:
            out.append(s + '\t' + M[s])
        elif s in KEEP:
            out.append(s + '\t' + s)
        else:
            miss.append(s)
    if miss:
        raise SystemExit('未覆盖 %d 条: %r' % (len(miss), miss[:20]))
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    io.open(DST, 'w', encoding='utf-8', newline='').write('\r\n'.join(out) + '\r\n')
    print('写出 %d 行 -> %s' % (len(out), DST))


if __name__ == '__main__':
    main()
