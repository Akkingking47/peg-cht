def main():
    with io.open(SRC, encoding="utf-8-sig", newline="") as f:
        raw = f.read()
    lines = raw.split("\n")
    if lines and lines[-1] == "":
        lines = lines[:-1]
    lines = [l.rstrip("\r") for l in lines]
    assert len(lines) == 400, len(lines)

    out = []
    kept = []
    for s in lines:
        if s in M:
            t = M[s]
        else:
            t = s
            kept.append(s)
        out.append(s + "\t" + t)

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with io.open(DST, "w", encoding="utf-8", newline="") as f:
        f.write("\r\n".join(out) + "\r\n")

    # ---------- 自检 ----------
    with io.open(DST, "rb") as f:
        data = f.read()
    assert not data.startswith(b"\xef\xbb\xbf"), "存在 BOM"
    text = data.decode("utf-8")
    assert text.endswith("\r\n"), "结尾非 CRLF"
    body = text[:-2]
    olines = body.split("\r\n")
    errs = []
    if len(olines) != len(lines):
        errs.append("行数不一致 %d != %d" % (len(olines), len(lines)))
    for i, (a, b) in enumerate(zip(lines, olines), 1):
        if b.count("\t") != 1:
            errs.append("第%d行 TAB 数 %d" % (i, b.count("\t")))
            continue
        src_col, dst_col = b.split("\t")
        if src_col != a:
            errs.append("第%d行 首列不符" % i)
        for ch in "/[]()":
            if src_col.count(ch) != dst_col.count(ch):
                errs.append("第%d行 符号 %s 数量 %d!=%d" % (i, ch, src_col.count(ch), dst_col.count(ch)))
    if b"\n\n" in data or b"\r\r" in data:
        errs.append("存在空行")
    if any(not l.strip() for l in lines):
        errs.append("输入含空行")

    if errs:
        print("FAIL")
        for e in errs[:40]:
            print(e)
        sys.exit(1)
    with io.open(DST, encoding="utf-8", newline="") as f:
        chk = [l.rstrip("\r") for l in f.read().split("\n") if l != ""]
    print("OK 行数=%d 输出=%s" % (len(chk), DST))
    print("保留原文行数=%d" % len(kept))
    for k in kept:
        print("KEEP\t" + k)

main()
