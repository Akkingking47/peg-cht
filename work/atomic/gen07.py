chk = open(DST, "rb").read()
assert not chk.startswith(b"\xef\xbb\xbf"), "输出含 BOM"
chk_lines = chk.split(b"\r\n")
if chk_lines and chk_lines[-1] == b"":
    chk_lines.pop()
print("输入行数:", n, "输出行数:", len(chk_lines))
assert len(chk_lines) == n, "行数不一致"

ok_tab = ok_orig = ok_sep = True
for i, (s, o) in enumerate(zip(src_txt, chk_lines)):
    t = o.decode("utf-8")
    parts = t.split("\t")
    if len(parts) != 2:
        ok_tab = False; print("TAB 异常行", i + 1, repr(t))
    else:
        if parts[0] != s:
            ok_orig = False; print("原文不符行", i + 1)
    zh = parts[-1]
    # 半角与全角括号成对换算后比较数量
    pairs = [("/", "/"), ("[", "["), ("]", "]"),
             ("(", "（"), (")", "）")]
    for a, b in pairs:
        if a in ("(", ")"):
            if zh.count(b) != s.count(a):
                ok_sep = False; print("分隔符不符行", i + 1, s, "->", zh)
        else:
            if zh.count(b) != s.count(a):
                ok_sep = False; print("分隔符不符行", i + 1, s, "->", zh)
    if zh.strip() == "":
        print("空译文中", i + 1)

print("每行1个TAB:", ok_tab, "| 首列==原文:", ok_orig, "| 分隔符一致:", ok_sep)
