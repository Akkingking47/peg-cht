# ---------------------------------------------------------------- 读入
raw = io.open(SRC, "r", encoding="utf-8", newline="").read()
body = raw.replace("\r\n", "\n")
lines = body.split("\n")
if lines and lines[-1] == "":
    lines = lines[:-1]

# ---------------------------------------------------------------- 生成
out, missing = [], []
for ln in lines:
    if ln in T:
        out.append(ln + "\t" + T[ln])
    else:
        out.append(ln + "\t" + ln)
        missing.append(ln)

data = "\r\n".join(out) + "\r\n"
with open(DST, "wb") as f:
    f.write(data.encode("utf-8"))

# ---------------------------------------------------------------- 自检
errs = []
b = open(DST, "rb").read()
if b[:3] == b"\xef\xbb\xbf":
    errs.append("BOM 存在")
if b.count(b"\r\n") != len(lines):
    errs.append("CRLF 数 %d != %d" % (b.count(b"\r\n"), len(lines)))

txt = b.decode("utf-8").split("\r\n")[:-1]
if len(txt) != len(lines):
    errs.append("行数 %d != %d" % (len(txt), len(lines)))

for i, (a, c) in enumerate(zip(lines, txt), 1):
    if c.count("\t") != 1:
        errs.append("行%d TAB 数 != 1" % i)
        continue
    col1, col2 = c.split("\t")
    if col1 != a:
        errs.append("行%d 原文不匹配: %r != %r" % (i, col1, a))
    if col2 == "":
        errs.append("行%d 译文为空" % i)
    for ch in "/[]()":
        if a.count(ch) != col2.count(ch):
            errs.append("行%d 符号 %s 数 %d != %d" % (i, ch, a.count(ch), col2.count(ch)))

print("输入行数:", len(lines))
print("输出行数:", len(txt))
print("字典命中:", len(lines) - len(missing))
print("落回原文(保留)行数:", len(missing))
if missing:
    print("--- 保留清单 ---")
    for m in missing:
        print("  ", m)
print("自检:", "通过" if not errs else "失败")
for e in errs:
    print("  !", e)
