KEEP = ["StuPio90/10.PzD", "TigerAbt501/10.PzD"]


def read_lines(path):
    with open(path, "rb") as f:
        data = f.read()
    assert not data.startswith(b"\xef\xbb\xbf"), "输入含 BOM"
    if b"\r\n" in data:
        crlf = True
        text = data.decode("utf-8")
    else:
        crlf = False
        text = data.decode("utf-8")
    raw = text.split("\r\n") if crlf else text.split("\n")
    if raw and raw[-1] == "":
        raw.pop()
    return raw, crlf


def main():
    src, crlf = read_lines(SRC)
    out = []
    missing = []
    for i, line in enumerate(src, 1):
        if line == "":
            out.append("\t")
            continue
        if line not in M:
            missing.append((i, line))
            out.append(line + "\t" + line)
        else:
            out.append(line + "\t" + M[line])
    if missing:
        print("!! 未映射行:")
        for i, l in missing:
            print("  ", i, repr(l))
        raise SystemExit(1)

    nl = "\r\n" if crlf else "\n"
    with open(DST, "w", encoding="utf-8", newline="") as f:
        f.write(nl.join(out) + nl)

    # ---- 自检 ----
    with open(DST, "rb") as f:
        blob = f.read()
    assert not blob.startswith(b"\xef\xbb\xbf"), "输出含 BOM"
    ok_crlf = blob.count(b"\r\n") == len(out) and b"\n" not in blob.replace(b"\r\n", b"")

    dst, _ = read_lines(DST)
    assert len(dst) == len(src), "行数不一致 %d vs %d" % (len(dst), len(src))

    for i, (a, b) in enumerate(zip(src, dst), 1):
        assert b.count("\t") == 1, "行%d TAB数!=1: %r" % (i, b)
        col1, col2 = b.split("\t")
        assert col1.encode("utf-8") == a.encode("utf-8"), "行%d 首列不等: %r" % (i, b)
        for ch in "/[]()":
            assert a.count(ch) == col2.count(ch), "行%d 符号%r数不等: %r" % (i, ch, b)

    print("行数: %d (输入 %d)" % (len(dst), len(src)))
    print("CRLF: %s" % ok_crlf)
    print("无BOM: True")
    print("TAB=1/行: True")
    print("首列逐字节一致: True")
    print("符号 / [ ] ( ) 数量一致: True")
    print("保留原文行 (%d): %s" % (len(KEEP), ", ".join(KEEP)))


main()
