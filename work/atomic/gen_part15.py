out.pop()
assert len(out) == len(lines), f"行数不一致 {len(out)} vs {len(lines)}"

def cnt(s, chs):
    return {c: s.count(c) for c in chs}

errs = []
for i, (a, b) in enumerate(zip(lines, out), 1):
    if b.count("\t") != 1:
        errs.append((i, "TAB 数 != 1", b))
        continue
    p, q = b.split("\t")
    if p != a:
        errs.append((i, "首列不等于原文", p))
    if cnt(p, "/[]()") != cnt(q, "/[]()"):
        errs.append((i, "分隔符数量不一致", f"{cnt(p,'/[]()')} vs {cnt(q,'/[]()')}"))

if errs:
    for e in errs[:20]:
        print("ERROR", e)
    raise SystemExit(f"自检失败，共 {len(errs)} 条")

