# ==== 正则：Capture all VHs ====
VH_RE = re.compile(r'^在\s*?(\d+)/(\d+)/(\d+)\s*?回合内(?:占领|夺取)(?:全部|所有)胜利点[，,]?\s*(?:可获得|以获得|以取得|可获)\s*(?:辉煌胜利/胜利/战术胜利|BV/V/TV)\s*。$')
VH_FMT = "在 {0}/{1}/{2} 回合内占领全部胜利点，可获得 BV/V/TV。"

def unify():
    stats = collections.Counter()
    for i in range(1, 13):
        op = os.path.join(OUT, f"out-{i:02d}.txt")
        raw = open(op, 'rb').read()
        has_trail = raw.endswith(b'\n')
        body = raw[:-1] if has_trail else raw
        out = []
        for ln in body.split(b'\n'):
            cr = ln.endswith(b'\r')
            core = ln[:-1] if cr else ln
            s = core.decode('utf-8')
            ns = s
            if s in VARIANTS:
                ns = VARIANTS[s]; stats['variant'] += 1
            else:
                m = VH_RE.match(s)
                if m:
                    ns = VH_FMT.format(*m.groups()); stats['vh'] += 1
            out.append(ns.encode('utf-8') + (b'\r' if cr else b''))
        open(op, 'wb').write(b'\n'.join(out) + (b'\n' if has_trail else b''))
    return stats

if __name__ == '__main__':
    print("统一:", dict(unify()))
