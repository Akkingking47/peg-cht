def main():
    with open(SRC, "rb") as f:
        raw = f.read()
    assert not raw.startswith(b"\xef\xbb\xbf"), "输入有 BOM"
    assert b"\r\n" in raw, "输入非 CRLF"
    lines = raw.split(b"\r\n")
    assert lines[-1] == b"", "输入末尾不是 CRLF"
    body = lines[:-1]
    body = [l.decode("utf-8") for l in body]

    missing = [s for s in body if s not in T]
    if missing:
        print("!!! 未覆盖条目:", file=sys.stderr)
        for m in missing:
            print(repr(m), file=sys.stderr)
        sys.exit(1)
    extra = [k for k in T if k not in set(body)]
    if extra:
        print("!!! 表中多余条目:", extra, file=sys.stderr)
        sys.exit(1)

    out = "\r\n".join(s + "\t" + T[s] for s in body) + "\r\n"
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "wb") as f:
        f.write(out.encode("utf-8"))
    print("written", DST, "rows", len(body))


if __name__ == "__main__":
    main()
