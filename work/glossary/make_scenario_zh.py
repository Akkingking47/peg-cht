def safe(s):
    """GBK 不含变音符字母（ä/é/ż…）⇒ 逐字折写为 ASCII，保证可编码。
    （这也解释了原文侧为何必须是单字节 latin-1：中文侧装不下西文变音符。）"""
    try:
        s.encode('gbk')
        return s, 0
    except UnicodeEncodeError:
        pass
    o, n = [], 0
    for ch in s:
        try:
            ch.encode('gbk'); o.append(ch); continue
        except UnicodeEncodeError:
            pass
        d = ''.join(c for c in unicodedata.normalize('NFKD', ch) if not unicodedata.combining(c))
        o.append(d if d else '?')
        n += 1
    return ''.join(o), n

