apply = '--apply' in sys.argv
os.makedirs(BK, exist_ok=True)
n = 0
for (ef, fn), tr in sorted(TRANS.items()):
    src = os.path.join(GAME, ef, 'SCENARIO', fn)
    if not os.path.exists(src):
        print('!! 原文缺失 %s' % src); continue
    raw = open(src, 'rb').read()
    lines = raw.replace(b'\r\n', b'\n').split(b'\n')
    out = []
    for i, ln in enumerate(lines):
        k = i + 1
        if k in tr:
            out.append(tr[k])
        else:
            try:
                out.append(ln.decode('utf-8'))
            except Exception:
                out.append(ln.decode('cp1252', 'replace'))
    text = '\r\n'.join(out)
    text, nfold = safe(text)
    data = text.encode('gbk')
    if nfold:
        print('     (折写非 GBK 字符 %d 个)' % nfold)
    if not apply:
        print('  [dry] %-14s %-22s %d 行 -> %d B' % (ef[6:], fn, len(lines), len(data)))
        continue
    dst = os.path.join(GAME, ef, 'TEXT-ZH', 'SCENARIO', fn)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    tmp = dst + '.new'
    open(tmp, 'wb').write(data)
    assert open(tmp, 'rb').read() == data, '回读校验失败 ' + dst
    os.replace(tmp, dst)
    # 原文归档（首次）
    bkp = os.path.join(BK, ef + '__' + fn)
    if not os.path.exists(bkp):
        open(bkp, 'wb').write(raw)
    n += 1
print(('已写出 %d 个中文侧场景文件' % n) if apply else '（dry-run，未写盘）')
