def main():
    rows = []
    for i, ln in enumerate(io.open(os.path.join(HERE, "_b6b_todo.tsv"), encoding="utf-8")):
        if i == 0:
            continue
        c = ln.rstrip("\r\n").split("\t")
        if len(c) >= 3 and c[0] == "多词":
            rows.append(c[1])
    print("todo 多词 %d 条 / 提供译文 %d 条" % (len(rows), len(DST)))
    if len(rows) != len(DST):
        raise SystemExit("!! 数量不符，禁止配对")
    bad = []
    for s, d in zip(rows, DST):
        if not d.strip() or "\t" in d:
            bad.append((s, d, "空/含制表符"))
        try:
            d.encode("gbk")
        except UnicodeEncodeError:
            bad.append((s, d, "GBK 不可编码"))
    if bad:
        print("!! 校验失败 %d 条:" % len(bad))
        for s, d, w in bad:
            print("   %-34s -> %-24s (%s)" % (s, d, w))
        raise SystemExit(1)
    print("校验通过 ✓")
    with io.open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write("src\tdst\n")
        for s, d in zip(rows, DST):
            f.write("%s\t%s\n" % (s, d))
    b = open(OUT, "rb").read()
    print("已写 %s（%d 条，BOM=%s）" % (os.path.basename(OUT), len(DST), b[:3] == b"\xef\xbb\xbf"))
    # 供复核：打印全部配对
    for n, (s, d) in enumerate(zip(rows, DST), 1):
        print("  %3d %-32s -> %s" % (n, s[:32], d))


if __name__ == "__main__":
    main()
