out_lines = []
nums = []
for num, text in pairs:
    nums.append(num)
    if num in VERBATIM:
        out_lines.append(num + "\t" + text)
        continue
    if num == "121":
        # 逐回合声望表：G=德军 R=俄军，仅替换国别代号，数字与结构原样保留
        t = re.sub(r"(\d+)G", r"\1德", text)
        t = re.sub(r"(\d+)R", r"\1俄", t)
        t = t.replace("G", "德").replace("R", "俄")
        out_lines.append(num + "\t" + t)
        continue
    if num not in T:
        raise SystemExit("缺少译文 num=" + num + " 原文=" + text)
    out_lines.append(num + "\t" + T[num])

assert len(nums) == len(set(nums)), "行号重复"
assert len(out_lines) == 114, "行数不是 114：" + str(len(out_lines))
assert not any("\t" in l.split("\t", 1)[1] for l in out_lines), "译文含 TAB"

if not os.path.isdir(os.path.dirname(DST)):
    os.makedirs(os.path.dirname(DST))
with io.open(DST, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out_lines) + "\n")

