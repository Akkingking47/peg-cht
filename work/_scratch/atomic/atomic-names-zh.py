# ---------------- driver ----------------
import os, io, sys, json, shutil, collections

GAME = r'D:/OpenPG2'
SRC = os.path.join(GAME, 'EFILE_ATOMIC')
DST = os.path.join(SRC, 'TEXT-ZH')
HERE = os.path.dirname(os.path.abspath(__file__))
CROSS = os.path.join(HERE, '_names-crossmap.json')


def main():
    apply_ = '--apply' in sys.argv
    cross = json.load(io.open(CROSS, encoding='utf-8'))
    table = dict(cross)
    table.update(ZH)          # 本 efile 专属译法优先于跨 efile 复用
    print('跨 efile 复用 %d 条 + 本层新增 %d 条 = 表 %d 条'
          % (len(cross), len(ZH), len(table)))

    raw = open(os.path.join(SRC, 'NamesEx.txt'), 'rb').read()
    text = raw.decode('cp1252')
    lines = text.split('\r\n')
    out = []
    hit = collections.Counter()
    miss = collections.Counter()
    for ln in lines:
        s = ln.strip()
        if not s or s.startswith('*'):
            out.append(ln)          # 分组头 / 空行原样保留
            continue
        z = table.get(s)
        if z is None:
            out.append(ln)
            miss[s] += 1
        else:
            out.append(ln.replace(s, z))
            hit[s] += 1

    print('NamesEx.txt %d 行  命中 %d 处/%d 种  未命中 %d 种/%d 处'
          % (len(out), sum(hit.values()), len(hit), len(miss), sum(miss.values())))
    for k, v in miss.most_common(40):
        print('    x%-4d %s' % (v, k))
    if miss:
        print('\n* 存在未命中，未写盘')
        return
    if not apply_:
        print('\n（dry-run，未写盘）')
        return

    data = '\r\n'.join(out).encode('gbk')
    os.makedirs(DST, exist_ok=True)
    tmp = os.path.join(DST, 'NamesEx.txt.new')
    open(tmp, 'wb').write(data)
    assert open(tmp, 'rb').read() == data, '回读不一致'
    os.replace(tmp, os.path.join(DST, 'NamesEx.txt'))
    print('已写出 NamesEx.txt  %d B (原 %d B)  CRLF=%d'
          % (len(data), len(raw), data.count(b'\r\n')))


if __name__ == '__main__':
    main()
