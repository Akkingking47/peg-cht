def main():
    raw = io.open(SRC, 'rb').read()
    assert raw[:3] != b'\xef\xbb\xbf', '输入含 BOM'
    src = raw.decode('utf-8')
    assert src.endswith('\r\n'), '输入结尾不是 CRLF'
    lines = src.split('\r\n')[:-1]
    assert len(lines) == 400, '输入行数 %d != 400' % len(lines)
    assert '' not in lines, '输入含空行'

    missing = [l for l in lines if l not in T]
    if missing:
        sys.stderr.write('缺少译文 %d 条:\n' % len(missing))
        for m in missing:
            sys.stderr.write('  %r\n' % m)
        return 1

    extra = set(T) - set(lines)
    if extra:
        sys.stderr.write('多余键 %d 条: %r\n' % (len(extra), sorted(extra)))
        return 1

    out = [l + '\t' + T[l] for l in lines]
    data = ('\r\n'.join(out) + '\r\n').encode('utf-8')
    assert data[:3] != b'\xef\xbb\xbf'
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with io.open(DST, 'wb') as f:
        f.write(data)

    # ---- 自检 ----
    back = io.open(DST, 'rb').read()
    assert back[:3] != b'\xef\xbb\xbf', '输出含 BOM'
    txt = back.decode('utf-8')
    ol = txt.split('\r\n')[:-1]
    report = []
    report.append('输出行数 = %d (输入 %d) -> %s' % (len(ol), len(lines), 'OK' if len(ol) == len(lines) else 'FAIL'))
    ok_tab = all(l.count('\t') == 1 for l in ol)
    report.append('每行恰好 1 个 TAB -> %s' % ('OK' if ok_tab else 'FAIL'))
    bad_col = [i + 1 for i, l in enumerate(ol) if l.split('\t', 1)[0] != lines[i]]
    report.append('第一列逐字节等于原文 -> %s' % ('OK' if not bad_col else 'FAIL %r' % bad_col[:10]))
    empty = [i + 1 for i, l in enumerate(ol) if l.split('\t', 1)[1] == '']
    report.append('无空译文 -> %s' % ('OK' if not empty else 'FAIL %r' % empty[:10]))
    sym_bad = []
    for i, l in enumerate(ol):
        a, b = l.split('\t', 1)
        for ch in '/[]()':
            if a.count(ch) != b.count(ch):
                sym_bad.append((i + 1, ch, a, b))
                break
    report.append('分隔符 / [ ] ( ) 数量一致 -> %s' % ('OK' if not sym_bad else 'FAIL %r' % sym_bad[:10]))
    trail = [i + 1 for i, l in enumerate(ol) if l != l.rstrip()]
    report.append('无行尾多余空格 -> %s' % ('OK' if not trail else 'FAIL %r' % trail))
    kept = [(i + 1, l.split('\t')[0]) for i, l in enumerate(ol) if l.split('\t', 1)[1] == l.split('\t', 1)[0]]
    report.append('保留原文条数 = %d' % len(kept))
    for n, t in kept:
        report.append('   行%d: %s' % (n, t))
    io.open(os.path.join(HERE, 'zh', '_check06.txt'), 'w', encoding='utf-8').write('\n'.join(report) + '\n')
    sys.stdout.write('\n'.join(report) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
