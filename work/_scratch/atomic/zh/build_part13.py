# 明确保留原文（值 = 原文）的少数条目，其余未列出的自动保留
KEEP = {"Nordfolda", "Nigg", "Norland"}

def main():
    raw = open(SRC, "rb").read()
    txt = raw.decode("utf-8").replace("\r\n", "\n").rstrip("\n")
    lines = txt.split("\n")
    if len(lines) != 400:
        print("输入行数异常:", len(lines)); sys.exit(1)

    out = []
    for src in lines:
        zh = M.get(src, src)
        out.append(src + "\t" + zh)

    data = "\r\n".join(out) + "\r\n"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "wb").write(data.encode("utf-8"))

    # ---- 自检 ----
    errs = []
    raw2 = open(OUT, "rb").read()
    if raw2[:3] == b"\xef\xbb\xbf":
        errs.append("存在 BOM")
    body = raw2.decode("utf-8")
    if not body.endswith("\r\n"):
        errs.append("末尾缺 CRLF")
    ob = body[:-2].split("\r\n")
    if len(ob) != len(lines):
        errs.append("行数不一致 %d != %d" % (len(ob), len(lines)))
    changed = 0
    for i, (a, b) in enumerate(zip(lines, ob)):
        if b.count("\t") != 1:
            errs.append("第%d行 TAB 数=%d" % (i + 1, b.count("\t")))
            continue
        s, z = b.split("\t")
        if s.encode("utf-8") != a.encode("utf-8"):
            errs.append("第%d行 首列不等于原文: %r" % (i + 1, s))
        if z == "":
            errs.append("第%d行 译文为空" % (i + 1))
        for ch in "/[]()":
            if s.count(ch) != z.count(ch):
                errs.append("第%d行 分隔符 %s 数量不一致 %d!=%d" % (i + 1, ch, s.count(ch), z.count(ch)))
        if a != z:
            changed += 1
        if z == a:
            KEEP.add(a)
    if b"\n\n" in raw2 or b"\r\n\r\n" in raw2:
        errs.append("存在空行")
    print("行数:", len(ob), "已译:", changed, "保留原文:", len(ob) - changed)
    print("错误数:", len(errs))
    for e in errs[:30]:
        print("  ", e)

main()
