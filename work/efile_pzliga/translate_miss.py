# 读 miss 清单核对覆盖
miss = []
with io.open("prematch-miss.tsv", encoding="utf-8-sig", newline="") as f:
    for i, ln in enumerate(f.read().replace("\r\n","\n").split("\n")):
        if i == 0 or not ln.strip(): continue
        c = ln.split("\t")
        miss.append(c[0])

