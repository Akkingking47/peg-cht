# 只替换文件里的一段文本（用于保留原有版式，如右对齐横幅）
REPL = {
    "G27_STA00l.txt": [("PORAŻKA!", "失败！")],
}


def main():
    miss = []
    for n in sorted(set(list(PROSE) + list(REPL))):
        sp = os.path.join(SRC, n)
        if not os.path.exists(sp):
            miss.append(n)
            continue
        raw = open(sp, encoding="utf-8", newline="").read()
        if n in REPL:
            out = raw
            for a, b in REPL[n]:
                assert a in out, (n, a)
                out = out.replace(a, b)
        else:
            if raw == "":
                out = ""
            else:
                nl = "\r\n" if "\r\n" in raw else "\n"
                src = raw.split(nl)
                trailing = src[-1] == ""
                if trailing:
                    src = src[:-1]
                tv = PROSE[n].split("\n") if PROSE[n] else []
                assert len(tv) == len(src), \
                    "行数不一致 %s 源%d 译%d" % (n, len(src), len(tv))
                out = nl.join(tv)
                if trailing and out != "":
                    out += nl
        with open(os.path.join(ZH, n), "w", encoding="utf-8", newline="") as f:
            f.write(out)
        print("wrote %-22s %4d -> %4d 字符" % (n, len(raw), len(out)))
    if miss:
        print("源文件缺失:", miss)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
