# 通名一致性表：src 结尾 → dst 结尾
TAIL_RULE = [
    ("Airfield", "机场"), ("Airfeild", "机场"), ("River", "河"), ("river", "河"),
    ("Sea", "海"), ("Port", "港"), ("Canal", "运河"), ("Island", "岛"),
    ("Factory", "工厂"), ("Station", "车站"), ("Railway", "铁路"), ("Outpost", "哨所"),
    ("Hill", "丘陵"), ("Line", "线"), ("Bay", "湾"),
]
# 例外：整体是描述性条目/事件名，非「专名+通名」结构，不受通名一致性约束
EXEMPT = {"Frozen River", "Battle at Don River", "Command Station"}


def main():
    rows = []
    for i, ln in enumerate(io.open(os.path.join(HERE, "_b6b_todo.tsv"), encoding="utf-8")):
        if i == 0:
            continue
        c = ln.rstrip("\r\n").split("\t")
        if len(c) >= 3 and c[0] == "通名可拆":
            rows.append(c[1])
    print("todo 通名可拆 %d 条 / 提供译文 %d 条" % (len(rows), len(DST)))
    if len(rows) != len(DST):
        raise SystemExit("!! 数量不符，禁止配对")
    bad = []
    for s, d in zip(rows, DST):
        s2 = s.strip()
        if s2 in EXEMPT:
            if not re.search(r"[\u4e00-\u9fff]", d):
                bad.append((s, d, "无汉字"))
            continue
        # 通名一致性
        for t, zh in TAIL_RULE:
            if s2.endswith(t) or s2.endswith(t + " ") or s2.endswith(" " + t):
                if not d.endswith(zh):
                    bad.append((s, d, "应以 %s 结尾" % zh))
                break
        else:
            if s2.startswith("Lake ") and not d.endswith("湖"):
                bad.append((s, d, "应以 湖 结尾"))
        if not re.search(r"[\u4e00-\u9fff]", d):
            bad.append((s, d, "无汉字"))
    if bad:
        print("!! 通名一致性校验失败 %d 条:" % len(bad))
        for s, d, w in bad:
            print("   %-36s -> %-24s (%s)" % (s, d, w))
        raise SystemExit(1)
    print("通名一致性校验通过 ✓")
    with io.open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write("src\tdst\n")
        for s, d in zip(rows, DST):
            f.write("%s\t%s\n" % (s, d))
    b = open(OUT, "rb").read()
    print("已写 %s（%d 条，BOM=%s）" % (os.path.basename(OUT), len(DST), b[:3] == b"\xef\xbb\xbf"))


if __name__ == "__main__":
    main()
