# ---------------------------------------------------------------- 工具
def orig_path(ef, fn):
    return os.path.join(ROOT, ef, "SCENARIO", fn)

def targets(ef, fn):
    """返回 (路径, 标签) 列表：SCENARIO 原文 + 语言目录副本"""
    out = [(os.path.join(ROOT, ef, "SCENARIO", fn), "SCENARIO")]
    lz = os.path.join(ROOT, ef, "TEXT-ZH", "SCENARIO", fn)
    out.append((lz, "TEXT-ZH"))
    return out

def star_line(ef, fn):
    """从原文件提取星号分隔线（若有）"""
    p = orig_path(ef, fn)
    if not os.path.exists(p):
        return None
    s = open(p, "rb").read().decode("latin-1")
    for l in s.replace("\r\n", "\n").split("\n"):
        t = l.strip()
        if t and set(t) == {"*"}:
            return t
    return None

def render(ef, fn, content):
    if STAR in content:
        st = star_line(ef, fn)
        if st is None:
            raise RuntimeError("译文含 @@STARS@@ 但原文无星号行")
        content = content.replace(STAR, st)
    return content.replace("\n", "\r\n").encode("gbk", errors="strict")

def verify(blob):
    if blob[:3] == b"\xEF\xBB\xBF":
        return "含 BOM"
    if blob.count(b"\r\n") == 0:
        return "无 CRLF"
    lone = blob.count(b"\n") - blob.count(b"\r\n")
    if lone:
        return "孤立 LF %d 个" % lone
    s = blob.decode("gbk")
    han = sum(1 for c in s if "\u4e00" <= c <= "\u9fff")
    if han == 0:
        return "无汉字"
    return None

def main():
    apply_ = "--apply" in sys.argv
    print("计划文件数:", len(DOCS))
    made = []
    errs = []
    for (ef, fn), content in sorted(DOCS.items()):
        op = orig_path(ef, fn)
        if not os.path.exists(op):
            errs.append("%s / %s  原文缺失" % (ef, fn)); continue
        try:
            blob = render(ef, fn, content)
        except Exception as e:
            errs.append("%s / %s  渲染失败: %s" % (ef, fn, e)); continue
        bad = verify(blob)
        if bad:
            errs.append("%s / %s  校验失败: %s" % (ef, fn, bad)); continue
        oh = hashlib.md5(open(op, "rb").read()).hexdigest()
        made.append((ef, fn, len(blob), blob, oh))
    print("准备就绪:", len(made), " 错误:", len(errs))
    for e in errs:
        print("  !!", e)
    if errs:
        print("存在错误，终止。"); return
    if not apply_:
        print("\n=== dry-run（未写入）===")
        for ef, fn, n, blob, oh in made:
            print("  %-18s %-26s -> %6d B" % (ef, fn, n))
        return
    print("\n=== 写入 ===")
    nw = 0
    for ef, fn, n, blob, oh in made:
        for path, tag in targets(ef, fn):
            d = os.path.dirname(path)
            if not os.path.isdir(d):
                os.makedirs(d)
            tmp = path + ".tmp"
            with open(tmp, "wb") as f:
                f.write(blob)
            back = open(tmp, "rb").read()
            if back != blob:
                errs.append("%s 回读不一致" % path); os.remove(tmp); continue
            os.replace(tmp, path)
            nw += 1
    print("  写入 %d 个文件" % nw)
    for e in errs:
        print("  !!", e)

if __name__ == "__main__":
    main()
