TOK = re.compile(r"%[sd]")


def main():
    raw = open(SRC, "rb").read()
    lines = raw.split(b"\r\n")
    n = len(lines)
    print(f"原文件：{SRC}")
    print(f"  行数(按 CRLF 切分) = {n}   字节 = {len(raw)}")

    # ---- 校验 1：覆盖性 ----
    missing = [i for i in range(1, n + 1) if i not in ZH and i not in KEEP]
    if missing:
        print(f"❌ 未覆盖行 {len(missing)} 条：{missing[:40]}")
        sys.exit(1)
    extra = [i for i in ZH if i > n]
    if extra:
        print(f"❌ 译文表含越界行号：{extra}")
        sys.exit(1)
    print(f"  译 {len(ZH)} 行 / 原样保留 {len(KEEP)} 行 / 合计 {len(ZH)+len(KEEP)} 行 ✅")

    # ---- 校验 2：格式符 ----
    bad_fmt = []
    for i, zh in ZH.items():
        en = lines[i - 1].decode("cp1252", "replace")
        if TOK.findall(en) != TOK.findall(zh):
            bad_fmt.append((i, en, zh))
    if bad_fmt:
        print("❌ printf 格式符不匹配：")
        for i, en, zh in bad_fmt:
            print(f"   行{i}  EN={en!r}  ZH={zh!r}")
        sys.exit(1)
    print("  格式符 %s/%d 顺序与个数全部保留 ✅")

    # ---- 校验 3：控制字符 ----
    bad_ctl = [(i, zh) for i, zh in ZH.items()
               if any(c in zh for c in "\r\n\t")]
    if bad_ctl:
        print(f"❌ 译文含控制字符：{bad_ctl}")
        sys.exit(1)
    print("  无 CR/LF/TAB 混入 ✅")

    # ---- 校验 4：术语一致性（整串精确匹配，避免「补充兵员」误伤）----
    hits = []
    for i, zh in ZH.items():
        for bad, why in BANNED.items():
            if zh.strip() == bad or zh.strip().rstrip("- ").strip() == bad:
                hits.append((i, bad, why))
    if hits:
        print("❌ 命中禁用译法：")
        for i, bad, why in hits:
            print(f"   行{i} 「{bad}」— {why}")
        sys.exit(1)
    print("  禁用译法扫描 0 命中 ✅")

    # ---- 产出成品 ----
    out = []
    for i in range(1, n + 1):
        if i in ZH:
            out.append(ZH[i].encode("gbk"))
        else:
            out.append(lines[i - 1])
    data = b"\r\n".join(out)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "wb").write(data)
    print(f"\n✅ 成品：{OUT}")
    print(f"   {len(data)} B（原 {len(raw)} B，{len(data)-len(raw):+d}）；"
          f"仍为 GBK/CRLF/无 BOM")

    # ---- 产出对照表 ----
    os.makedirs(os.path.dirname(TSV), exist_ok=True)
    with open(TSV, "w", encoding="utf-8", newline="\n") as f:
        f.write("# PeG Gui030.txt 行级对照表（2026-10-10）\n")
        f.write("# 依据 peg/research/ui-glossary.tsv；★=本次术语订正\n")
        f.write("行号\t原文\t译文\t备注\n")
        for i in range(1, n + 1):
            en = lines[i - 1].decode("cp1252", "replace")
            zh = ZH.get(i, en)
            note = ""
            if zh == en:
                note = "原样保留"
            elif any(b in zh for b in BANNED):
                note = "★"
            f.write(f"{i}\t{en}\t{zh}\t{note}\n")
    print(f"✅ 对照表：{TSV}")


if __name__ == "__main__":
    main()
